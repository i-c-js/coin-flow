// Runs the CoinFlow forecasting experiment and writes research/results.json + research/RESULTS.md.
// Usage: npm run benchmark
import { writeFileSync } from "node:fs";
import { METHODS, type MethodName } from "../src/lib/forecast/methods";
import { evaluateLedger } from "../src/lib/forecast/evaluate";
import { generateLedger, toWeeks, PROFILES, type Profile } from "../src/lib/forecast/synthetic";
import { mean, median, wilcoxonSignedRank } from "../src/lib/forecast/stats";

const LEDGERS_PER_PROFILE = 30;
const TREND_PROFILES: Profile[] = ["rising", "falling"];

type Row = { profile: Profile; seed: number; method: MethodName; mae: number; rmse: number; smape: number; msPerForecast: number; forecasts: number };
const rows: Row[] = [];

PROFILES.forEach((profile, p) => {
  for (let i = 0; i < LEDGERS_PER_PROFILE; i++) {
    const seed = (p + 1) * 1000 + i;
    const weeks = toWeeks(generateLedger(profile, seed));
    for (const method of METHODS) rows.push({ profile, seed, method, ...evaluateLedger(weeks, method) });
  }
});

const pick = (method: MethodName, profiles: Profile[] = PROFILES) =>
  rows.filter((r) => r.method === method && profiles.includes(r.profile));

const summary = (list: Row[]) => ({
  mae: mean(list.map((r) => r.mae)),
  rmse: mean(list.map((r) => r.rmse)),
  smape: mean(list.map((r) => r.smape)),
  msPerForecast: mean(list.map((r) => r.msPerForecast)),
});

const overall = Object.fromEntries(METHODS.map((m) => [m, summary(pick(m))]));
const byProfile = Object.fromEntries(PROFILES.map((p) => [p, Object.fromEntries(METHODS.map((m) => [m, summary(pick(m, [p]))]))]));

// Paired comparison: same ledgers, method a vs method b (negative difference = a is better).
function compare(a: MethodName, b: MethodName, profiles: Profile[] = PROFILES) {
  const maeA = pick(a, profiles).map((r) => r.mae);
  const maeB = pick(b, profiles).map((r) => r.mae);
  const test = wilcoxonSignedRank(maeA, maeB);
  return {
    a, b, profiles: profiles.length === PROFILES.length ? "all" : profiles.join("+"),
    maeA: mean(maeA), maeB: mean(maeB),
    improvementPct: (100 * (mean(maeB) - mean(maeA))) / mean(maeB),
    medianDifference: median(maeA.map((x, i) => x - maeB[i])),
    aBetterOnLedgers: maeA.filter((x, i) => x < maeB[i]).length,
    ledgers: maeA.length,
    ...test,
  };
}

const tests = [
  compare("HOLT", "SMA"),
  compare("HOLT", "SMA", TREND_PROFILES),
  compare("HOLT", "SES"),
  compare("SES", "SMA"),
  compare("SMA", "NAIVE"),
  compare("SES", "NAIVE"),
  compare("HOLT", "NAIVE"),
];
// Exploratory comparisons, added after H1 was rejected (not part of the pre-registered hypotheses).
const exploratory = [compare("DAMPED", "HOLT"), compare("DAMPED", "SMA"), compare("DAMPED", "SMA", TREND_PROFILES), compare("DAMPED", "SES")];

// Sensitivity analysis (exploratory): does trend modelling win when spending is less noisy?
// Rising ledgers only, same seeds, different amounts of day-to-day noise.
const NOISE_LEVELS = [0.05, 0.15, 0.3, 0.45];
const sensitivity = NOISE_LEVELS.map((noise) => {
  const maeOf = (method: MethodName) =>
    mean(Array.from({ length: LEDGERS_PER_PROFILE }, (_, i) => evaluateLedger(toWeeks(generateLedger("rising", 2000 + i, noise)), method).mae));
  return { noise, ...Object.fromEntries(METHODS.map((m) => [m, maeOf(m)])) } as { noise: number } & Record<MethodName, number>;
});

const h1All = tests[0];
const h1Trend = tests[1];
const h1Supported = h1All.maeA < h1All.maeB && h1All.p < 0.05 && h1Trend.improvementPct >= 10;
const h2Supported = tests.slice(4).every((t) => t.maeA < t.maeB && t.p < 0.05);
const PREREGISTERED: MethodName[] = ["NAIVE", "SMA", "SES", "HOLT"];
const best = METHODS.reduce((x, y) => (overall[x].mae <= overall[y].mae ? x : y));

const results = {
  date: new Date().toISOString().slice(0, 10),
  config: { ledgersPerProfile: LEDGERS_PER_PROFILE, profiles: PROFILES, ledgers: LEDGERS_PER_PROFILE * PROFILES.length, weeksPerLedger: 26, firstForecastWeek: 8, forecastsPerMethod: rows.filter((r) => r.method === "SMA").reduce((s, r) => s + r.forecasts, 0) },
  overall, byProfile, tests, exploratory, sensitivity,
  hypotheses: { h1Supported, h2Supported, bestMethod: best },
};
writeFileSync("research/results.json", JSON.stringify(results, null, 2) + "\n");

// ---------- Human-readable report ----------
const lei = (x: number) => x.toFixed(1);
const pValue = (p: number) => (p < 0.001 ? "< 0.001" : p.toFixed(3));
let md = `# Results (generated by \`npm run benchmark\` on ${results.date})\n\n`;
md += `${results.config.ledgers} ledgers × 18 weekly forecasts = ${results.config.forecastsPerMethod} forecasts per method.\n\n`;
md += `## Overall (lower is better)\n\n| Method | MAE (lei/week) | RMSE | sMAPE % | ms per forecast |\n|---|---|---|---|---|\n`;
for (const m of METHODS) md += `| ${m}${PREREGISTERED.includes(m) ? "" : " *"} | ${lei(overall[m].mae)} | ${lei(overall[m].rmse)} | ${overall[m].smape.toFixed(1)} | ${overall[m].msPerForecast.toFixed(4)} |\n`;
md += `\n\* exploratory method, added after the main experiment.\n`;
md += `\n## MAE by spending profile (lei/week)\n\n| Profile | ${METHODS.join(" | ")} | Best |\n|---|${METHODS.map(() => "---").join("|")}|---|\n`;
for (const p of PROFILES) {
  const bestHere = METHODS.reduce((x, y) => (byProfile[p][x].mae <= byProfile[p][y].mae ? x : y));
  md += `| ${p} | ${METHODS.map((m) => lei(byProfile[p][m].mae)).join(" | ")} | ${bestHere} |\n`;
}
md += `\n## Statistical tests (Wilcoxon signed-rank, paired by ledger)\n\n| A vs B | Ledgers | MAE A | MAE B | A better by | A better on | z | p | effect r |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const t of tests) md += `| ${t.a} vs ${t.b} (${t.profiles}) | ${t.ledgers} | ${lei(t.maeA)} | ${lei(t.maeB)} | ${t.improvementPct.toFixed(1)} % | ${t.aBetterOnLedgers}/${t.ledgers} | ${t.z.toFixed(2)} | ${pValue(t.p)} | ${t.r.toFixed(2)} |\n`;
md += `\n## Exploratory comparisons (added after H1 was rejected — not pre-registered)\n\n| A vs B | Ledgers | MAE A | MAE B | A better by | A better on | z | p | effect r |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const t of exploratory) md += `| ${t.a} vs ${t.b} (${t.profiles}) | ${t.ledgers} | ${lei(t.maeA)} | ${lei(t.maeB)} | ${t.improvementPct.toFixed(1)} % | ${t.aBetterOnLedgers}/${t.ledgers} | ${t.z.toFixed(2)} | ${pValue(t.p)} | ${t.r.toFixed(2)} |\n`;
md += `\n## Sensitivity: rising ledgers at different noise levels (MAE, lei/week)\n\n| Daily noise σ | ${METHODS.join(" | ")} | Best |\n|---|${METHODS.map(() => "---").join("|")}|---|\n`;
for (const row of sensitivity) {
  const bestHere = METHODS.reduce((x, y) => (row[x] <= row[y] ? x : y));
  md += `| ${row.noise}${row.noise === 0.45 ? " (main)" : ""} | ${METHODS.map((m) => lei(row[m])).join(" | ")} | ${bestHere} |\n`;
}
md += `\n## Hypotheses\n\n- **H1** (HOLT beats SMA, p < 0.05, ≥ 10 % better on trend ledgers): **${h1Supported ? "SUPPORTED" : "NOT SUPPORTED"}**\n- **H2** (every smoothing method beats NAIVE, p < 0.05): **${h2Supported ? "SUPPORTED" : "NOT SUPPORTED"}**\n- Lowest overall error: **${best}**\n`;
writeFileSync("research/RESULTS.md", md);
console.log(md);
